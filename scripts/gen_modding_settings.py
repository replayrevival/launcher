"""Regenerates the "Settings and tweaks you can change" tables in docs/MODDING.md from config/settings.json,
so the guide never goes stale.

  python scripts/gen_modding_settings.py [--settings config/settings.json] [--doc docs/MODDING.md] [--check]

The tables sit between <!-- SETTINGS:BEGIN --> and <!-- SETTINGS:END --> in the guide; everything outside is left alone.
--check prints nothing and exits 1 if the guide is out of date (use it before a release)."""
import argparse, json, os, sys

BEGIN, END = '<!-- SETTINGS:BEGIN (generated by scripts/gen_modding_settings.py from config/settings.json: do not edit by hand) -->', '<!-- SETTINGS:END -->'
PAGES = [('video', 'Video'), ('enhance', 'Enhancements')]
FILES = {'video': 'ste_video.ini', 'window': 'ste_video.ini', 'audio': 'ste_video.ini', 'enhance': 'ste_enhance.ini', 'input': 'ste_enhance.ini'}


def md(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def keyinfo(s, key):
    k = s['keys'].get(key, {})
    sec = k.get('s', key.split('.')[0])
    name = k.get('k', key.split('.', 1)[-1])
    f = k.get('f')
    f = {'video': 'ste_video.ini', 'enhance': 'ste_enhance.ini'}.get(f, f) or FILES.get(sec, 'ste_' + sec + '.ini')
    return f, sec, name, k.get('d')


def row_values(r):
    if r.get('type') == 'toggle':
        return 'ON / OFF', list(r.get('on', {}))[:1]
    ch = r.get('choices') or []
    keys = []
    for c in ch:
        for k in c.get('set', {}):
            if k not in keys:
                keys.append(k)
    labels = ', '.join(c['label'] for c in ch)
    return labels, keys[:1]


def build(s):
    out = []
    for page, title in PAGES:
        out.append(f'### {title}\n')
        out.append('| Option (launcher and in-game menu) | What it does | Values | Setting in the ini file | Default |')
        out.append('|---|---|---|---|---|')
        group = ''
        for r in s['pages'][page]:
            if 'group' in r:
                group = r['group']
                note = r.get('note', '')
                out.append(f'| **{md(group)}** | {md(note)} | | | |')
                continue
            vals, keys = row_values(r)
            if r.get('special'):
                vals = 'chosen from what your monitor reports'
            ini = ''
            default = ''
            if keys:
                f, sec, name, d = keyinfo(s, keys[0])
                ini = f'`{f}` `[{sec}]` `{name}`'
                default = '' if d is None else (f'`{d}`')
            need = f' (shown only when the game reports `{r["needs"]}`)' if r.get('needs') else ''
            out.append(f'| {md(r.get("label", r["id"]))} | {md(r.get("hint", ""))}{need} | {md(vals)} | {ini} | {default} |')
        out.append('')
    out.append('### Presets\n')
    out.append('| Preset | What it does |')
    out.append('|---|---|')
    for p in s.get('presets', []):
        out.append(f'| {md(p["name"])} | {md(p.get("description", ""))} |')
    out.append('')
    out.append('Every key can also be set for one run with the environment variable `STE_<SECTION>_<KEY>` (see the game project\'s `docs/LAUNCHER_INTERFACE.md`). Off, or the first value, is the original game.')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument('--settings', default=os.path.join(root, 'config', 'settings.json'))
    ap.add_argument('--doc', default=os.path.join(root, 'docs', 'MODDING.md'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    s = json.load(open(a.settings, encoding='utf-8-sig'))
    text = open(a.doc, encoding='utf-8-sig').read().replace('\r\n', '\n')
    if BEGIN.split(' (')[0] not in text or END not in text:
        sys.exit('The guide has no SETTINGS:BEGIN / SETTINGS:END markers.')
    i = text.index(BEGIN.split(' (')[0])
    j = text.index(END)
    new = text[:i] + BEGIN + '\n' + build(s) + text[j:]
    if a.check:
        sys.exit(0 if new == text else 1)
    open(a.doc, 'w', encoding='utf-8', newline='\n').write(new)
    print('updated', a.doc)


if __name__ == '__main__':
    main()
